-- Sales follow-up: who assigned a deal, its next action, pause / loss / win
-- details, a quote link, and an append-only history of contact attempts.

alter table public.deals
    add column assigned_by bigint,
    add column next_action text,
    add column next_action_date date,
    add column reminders_muted boolean not null default false,
    add column attempts_reset_at timestamp with time zone,
    add column resume_date date,
    add column lost_reason text,
    add column po_number text,
    add column po_date date,
    add column po_url text,
    add column quote_number text,
    add column quote_amount bigint,
    add column quote_url text,
    add column quote_sent_date date;

alter table public.deals
    add constraint deals_assigned_by_fkey foreign key (assigned_by) references public.sales(id);

create table public.deal_activities (
    id bigint generated by default as identity primary key,
    deal_id bigint not null,
    sales_id bigint,
    date timestamp with time zone not null default now(),
    channel text not null,
    answered boolean not null,
    notes text,
    constraint deal_activities_channel_check check (channel in ('call', 'whatsapp', 'email', 'visit'))
);

alter table public.deal_activities
    add constraint deal_activities_deal_id_fkey foreign key (deal_id) references public.deals(id) on update cascade on delete cascade;

alter table public.deal_activities
    add constraint deal_activities_sales_id_fkey foreign key (sales_id) references public.sales(id);

create index deal_activities_deal_id_date_idx on public.deal_activities using btree (deal_id, date desc);

create or replace trigger set_deal_activities_sales_id_trigger
    before insert on public.deal_activities
    for each row execute function public.set_sales_id_default();

alter table public.deal_activities enable row level security;

-- Append-only contact history: no update or delete policy for app users
create policy "Enable read access for authenticated users" on public.deal_activities for select to authenticated using (true);
create policy "Enable insert for authenticated users only" on public.deal_activities for insert to authenticated with check (true);

grant select, insert on table public.deal_activities to authenticated;
grant all on table public.deal_activities to service_role;

grant usage, select on sequence public.deal_activities_id_seq to authenticated;
grant all on sequence public.deal_activities_id_seq to service_role;
